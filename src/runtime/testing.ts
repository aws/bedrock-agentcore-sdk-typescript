import { Buffer } from 'buffer'
import { randomUUID } from 'crypto'
import type { OutgoingHttpHeaders } from 'http'
import type { z } from 'zod'
import type { BedrockAgentCoreApp } from './app.js'
import type { HealthCheckResponse } from './types.js'

/**
 * In-process client that drives a BedrockAgentCoreApp without binding a port.
 */
export interface TestClient {
  /**
   * Sends a request to `POST /invocations`.
   *
   * @param body - Request payload, JSON encoded unless it is a string or Buffer, which are sent as is
   * @param options - Session ID, request ID, and headers AgentCore Runtime would send
   * @returns Status, headers, decoded body, and parsed SSE events
   */
  invoke(body: unknown, options?: TestInvokeOptions): Promise<TestInvokeResult>

  /**
   * Sends a request to `GET /ping`.
   *
   * @returns The health check response
   */
  ping(): Promise<HealthCheckResponse>
}

/**
 * Request values AgentCore Runtime would send with an invocation.
 */
export interface TestInvokeOptions {
  /**
   * Session ID header value, a random UUID when omitted.
   */
  sessionId?: string

  /**
   * Request ID header value, generated by the app when omitted.
   */
  requestId?: string

  /**
   * Extra request headers, which override the defaults.
   */
  headers?: Record<string, string>
}

/**
 * Response of an in-process invocation.
 */
export interface TestInvokeResult {
  /**
   * HTTP status code.
   */
  status: number

  /**
   * Response headers.
   */
  headers: OutgoingHttpHeaders

  /**
   * Response body, parsed when it is JSON, a Buffer when it is binary, otherwise text.
   */
  body: unknown

  /**
   * Parsed SSE events, empty unless the response is a stream.
   */
  events: TestEvent[]
}

/**
 * One parsed Server-Sent Event.
 */
export interface TestEvent {
  /**
   * Event name, `message` when the stream does not name it.
   */
  event: string

  /**
   * Event data, parsed when it is JSON, otherwise text.
   */
  data: unknown

  /**
   * Event ID, when the stream sets one.
   */
  id?: string
}

const SESSION_ID_HEADER = 'x-amzn-bedrock-agentcore-runtime-session-id'
const REQUEST_ID_HEADER = 'x-amzn-bedrock-agentcore-runtime-request-id'

/**
 * Creates an in-process test client for a BedrockAgentCoreApp.
 *
 * @param app - The app under test
 * @returns A client that invokes and pings the app without binding a port
 */
export function createTestClient<TSchema extends z.ZodSchema>(app: BedrockAgentCoreApp<TSchema>): TestClient {
  return {
    async invoke(body, options = {}): Promise<TestInvokeResult> {
      const { payload, contentType } = encodeBody(body)
      const server = await app['_prepare']()
      const response = await server.inject({
        method: 'POST',
        url: '/invocations',
        payload,
        headers: {
          accept: 'text/event-stream, application/json',
          'content-type': contentType,
          [SESSION_ID_HEADER]: options.sessionId ?? randomUUID(),
          ...(options.requestId !== undefined && { [REQUEST_ID_HEADER]: options.requestId }),
          ...options.headers,
        },
      })
      const type = mediaType(response.headers['content-type'])
      return {
        status: response.statusCode,
        headers: response.headers,
        body: decodeBody(type, response.body, response.rawPayload),
        events: type === 'text/event-stream' ? parseEvents(response.body) : [],
      }
    },

    async ping(): Promise<HealthCheckResponse> {
      const server = await app['_prepare']()
      const response = await server.inject({ method: 'GET', url: '/ping' })
      return response.json<HealthCheckResponse>()
    },
  }
}

function encodeBody(body: unknown): { payload: string | Buffer; contentType: string } {
  if (Buffer.isBuffer(body)) {
    return { payload: body, contentType: 'application/octet-stream' }
  }
  if (typeof body === 'string') {
    return { payload: body, contentType: 'text/plain' }
  }
  return { payload: JSON.stringify(body) ?? '', contentType: 'application/json' }
}

function mediaType(header: string | number | string[] | undefined): string {
  return String(header ?? '')
    .split(';')[0]!
    .trim()
    .toLowerCase()
}

function decodeBody(type: string, text: string, raw: Buffer): unknown {
  if (type === 'application/json') {
    return text === '' ? undefined : parseData(text)
  }
  if (type === 'application/octet-stream') {
    return raw
  }
  return text
}

function parseEvents(text: string): TestEvent[] {
  const events: TestEvent[] = []
  let data: string[] = []
  let event = 'message'
  let id: string | undefined

  for (const line of [...text.split(/\r\n|\r|\n/), '']) {
    if (line === '') {
      if (data.length > 0) {
        events.push({ event, data: parseData(data.join('\n')), ...(id !== undefined && { id }) })
      }
      data = []
      event = 'message'
      id = undefined
      continue
    }
    const colon = line.indexOf(':')
    const field = colon === -1 ? line : line.slice(0, colon)
    const raw = colon === -1 ? '' : line.slice(colon + 1)
    const value = raw.startsWith(' ') ? raw.slice(1) : raw
    if (field === 'data') data.push(value)
    else if (field === 'event') event = value
    else if (field === 'id') id = value
  }

  return events
}

function parseData(text: string): unknown {
  try {
    return JSON.parse(text)
  } catch {
    return text
  }
}
